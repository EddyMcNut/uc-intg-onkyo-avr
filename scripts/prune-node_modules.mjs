// Removes runtime-unused build outputs from shipped dependencies to keep the integration
// tarball small. Only targets files that are provably not loaded by the driver at runtime.
// Usage: node scripts/prune-node_modules.mjs [node_modules_path] (default: node_modules)
import { rmSync, existsSync } from "node:fs";
import { resolve, join } from "node:path";

const root = process.argv[2] ?? "node_modules";
const nmPath = resolve(root);

if (!existsSync(nmPath)) {
  console.error(`[prune-node_modules] node_modules not found at ${nmPath}`);
  process.exit(1);
}

// @unfoldedcircle/integration-api ships redundant ESM/UMD/test builds in dist/. Node only
// ever loads the CJS build (package "main" → dist/cjs/index.js); the rest is dead weight.
const integrationApiDist = join(nmPath, "@unfoldedcircle", "integration-api", "dist");
const pruneTargets = ["mjs", "lib", "index.js", "test", "cjs/test"];

let removed = 0;
if (existsSync(integrationApiDist)) {
  for (const target of pruneTargets) {
    const p = join(integrationApiDist, target);
    if (existsSync(p)) {
      rmSync(p, { recursive: true, force: true });
      console.log(`[prune-node_modules] removed ${p}`);
      removed++;
    }
  }
}

// Sanity check: the runtime entry must still be present after pruning.
const runtimeEntry = join(integrationApiDist, "cjs", "index.js");
if (!existsSync(runtimeEntry)) {
  console.error(`[prune-node_modules] FATAL: runtime entry missing after prune: ${runtimeEntry}`);
  process.exit(1);
}
console.log(`[prune-node_modules] done (${removed} target(s) removed), runtime entry intact: ${runtimeEntry}`);
